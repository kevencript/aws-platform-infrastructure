#!/bin/sh
# Checks the files under environments/. terraform validate never reads them,
# so without this script nothing would read them before a real plan.
#
#   1. Every environment has the same three files, with the same keys.
#   2. The values that terraform.tfvars and bootstrap.tfvars share are equal.
#   3. Each variable file satisfies the variables of its stack: no unknown
#      name, no missing value, the right types, and the validation rules of
#      the stack's own variables.
#
# The rules inside the root module's child modules are not evaluated here:
# during validate, a value the root module passes on to a module is unknown,
# so the module's rules wait for a plan. A plan runs them before any call to
# AWS, and the pipeline plans every pull request.
#
# Check 3 writes a throwaway configuration that calls each stack as a module
# and passes the content of its variable file as the module's arguments, then
# runs terraform validate on it. A variable file and a module's arguments use
# the same syntax, which is why this needs no credentials and no plan.
#
# Because each stack is called as a module, a block that Terraform accepts
# only in a root module, such as an import block on Terraform 1.5, makes
# this check fail although the stack itself validates.
#
# The content of backend.hcl is not checked beyond its keys: only a real
# terraform init reads it.

set -eu

TERRAFORM="${TERRAFORM:-terraform}"
CHECK_DIR=".environment-check"

cd "$(dirname "$0")/.."

fail() {
  echo "environments: $*" >&2
  exit 1
}

# Top-level names of a file, one per line. terraform fmt puts every top-level
# name at the start of a line, which this pattern relies on.
keys() {
  sed -n 's/^\([a-z_][a-z0-9_]*\)[[:space:]]*=.*/\1/p' "$1" | sort
}

# Value of one top-level name, as written in the file.
value() {
  sed -n "s/^$2[[:space:]]*=[[:space:]]*//p" "$1"
}

# The environments are the directories under environments/. The first one is
# the reference the others are compared with.
set --
for directory in environments/*/; do
  set -- "$@" "$(basename "$directory")"
done
reference="$1"

# 1. Same files and same keys everywhere.
for file in terraform.tfvars bootstrap.tfvars backend.hcl; do
  for env in "$@"; do
    [ -f "environments/$env/$file" ] || fail "environments/$env/$file is missing"
    [ "$(keys "environments/$env/$file")" = "$(keys "environments/$reference/$file")" ] ||
      fail "environments/$env/$file and environments/$reference/$file do not have the same keys"
  done
done

# 2. A value written in both variable files of an environment must agree.
for env in "$@"; do
  root_file="environments/$env/terraform.tfvars"
  bootstrap_file="environments/$env/bootstrap.tfvars"
  for key in $(keys "$root_file"); do
    if grep -q "^$key[[:space:]]*=" "$bootstrap_file"; then
      [ "$(value "$root_file" "$key")" = "$(value "$bootstrap_file" "$key")" ] ||
        fail "$key differs between $root_file and $bootstrap_file"
    fi
  done
done

# 3. Each variable file against the variables of its stack.
mkdir -p "$CHECK_DIR"
cp .terraform.lock.hcl "$CHECK_DIR/"
{
  echo "# Generated by tools/check-environments.sh. Safe to delete."
  for env in "$@"; do
    printf '\nmodule "root_%s" {\n  source = "../"\n\n' "$env"
    cat "environments/$env/terraform.tfvars"
    printf '}\n\nmodule "bootstrap_%s" {\n  source = "../bootstrap"\n\n' "$env"
    cat "environments/$env/bootstrap.tfvars"
    printf '}\n'
  done
} >"$CHECK_DIR/main.tf"

"$TERRAFORM" -chdir="$CHECK_DIR" init -no-color -backend=false -input=false -lockfile=readonly >/dev/null &&
  "$TERRAFORM" -chdir="$CHECK_DIR" validate -no-color >/dev/null ||
  fail "the generated configuration is not valid. The usual cause is a variable file that does not match its stack. Modules above are named <stack>_<environment>; line numbers refer to $CHECK_DIR/main.tf"

echo "environments: ok ($*) with $("$TERRAFORM" version | head -n 1)"
